"""Prepare an isolated Codex CLI profile for the BAGO5 workflow entry."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ENTRY = "bago5-flujo-trabajo"
NAMES = {ENTRY, "bago5-governed-classic:" + ENTRY, "bago5-workflow", "bago5-governed-classic:bago5-workflow"}
ENTRY_FILE = Path(__file__).resolve().parents[1] / "SKILL.md"
BUDGET = 32000
TAG = "# Generated by BAGO5 Workflow for this Codex CLI catalog."
NAME = r"[A-Za-z0-9_.-]+(?::[A-Za-z0-9_.-]+)?"


def executable(value):
    if value:
        found = shutil.which(value)
    elif os.name == "nt":
        found = shutil.which("codex.exe")
        wrapper = shutil.which("codex.cmd")
        if not found and wrapper:
            vendor = Path(wrapper).parent / "node_modules/@openai/codex/node_modules/@openai"
            choices = list(vendor.glob("codex-win32-*/vendor/*/bin/codex.exe"))
            if len(choices) == 1:
                found = str(choices[0])
    else:
        found = shutil.which("codex")
    if not found or (os.name == "nt" and Path(found).suffix.lower() != ".exe"):
        raise ValueError("Select the native Codex executable with --codex.")
    return str(Path(found).resolve(strict=True))


def parse_catalog(messages):
    blocks = []
    for message in messages:
        if message.get("role") != "developer":
            continue
        for item in message.get("content", []):
            if item.get("type") == "input_text":
                content = item["text"]
                if content.count("<skills_instructions>") != content.count("</skills_instructions>"):
                    raise ValueError("Incomplete developer skill catalog block.")
                blocks.extend(re.findall(r"<skills_instructions>(.*?)</skills_instructions>", content, re.S))
    if len(blocks) != 1:
        raise ValueError("No unique, complete developer skill catalog.")
    block = blocks[0]
    headings = ["### Skill roots", "### Available skills"]
    if any(block.count(h) != 1 for h in headings):
        raise ValueError("Incomplete skill catalog headings.")
    roots_text, entries_text = block.split(headings[0])[1].split(headings[1])
    roots = {}
    for line in roots_text.strip().splitlines():
        match = re.fullmatch(r"- `(r\d+)` = `([^\x00`]+)`", line)
        if not match or match[1] in roots or not Path(match[2]).is_absolute():
            raise ValueError("Unrecognized or ambiguous catalog root.")
        roots[match[1]] = Path(match[2]).resolve(strict=True)
    skills = []
    for line in entries_text.strip().splitlines():
        match = re.fullmatch(r"- (" + NAME + r"): .* \(file: (r\d+)/(.+/SKILL\.md)\)", line)
        if not match or match[2] not in roots:
            raise ValueError("Unrecognized or incomplete catalog entry.")
        root = roots[match[2]]
        relative = Path(match[3])
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("Unsafe skill path.")
        path = (root / relative).resolve(strict=True)
        if not path.is_relative_to(root) or not path.is_file():
            raise ValueError("Catalog entry is outside its root or is not a file.")
        skills.append((match[1], path))
    if not skills or len({path for _, path in skills}) != len(skills):
        raise ValueError("Empty or ambiguous skill catalog.")
    if re.search(r"(?im)^\s*(?:warning|note|notice|some skills|skills (?:were|omitted|truncated)|\[\.\.\.)",block):
        raise ValueError("Catalog reports an incomplete listing.")
    return skills


def catalog(cli, env, profile=None):
    command = [cli, "--no-daemon"]
    if profile:
        command += ["--profile", profile]
    command += ["-c", f"skills.max_context_tokens={BUDGET}", "debug", "prompt-input", "List available skills."]
    result = subprocess.run(command, env=env, capture_output=True, timeout=120)
    if result.returncode:
        raise ValueError(f"Codex prompt discovery failed with code {result.returncode}.")
    if re.search(rb"(?:skills?[^\n]*(?:omitted|truncated)|incomplete skill catalog)", result.stderr, re.I):
        raise ValueError("CLI reports incomplete skill discovery.")
    return parse_catalog(json.loads(result.stdout))


def prepare(cli, home, entry):
    home = home.resolve(strict=True)
    if not home.is_dir() or not entry.is_file():
        raise ValueError("An existing Codex home and installed workflow entry are required.")
    entry = entry.resolve(strict=True)
    env = dict(os.environ, CODEX_HOME=str(home))
    before = catalog(cli, env)
    selected = [skill for skill in before if skill[1] == entry and skill[0] in NAMES]
    if len(selected) != 1:
        raise ValueError("Installed BAGO5 workflow entry was not uniquely discovered.")
    lines = [TAG, f"skills.max_context_tokens = {BUDGET}", ""]
    for _, path in sorted(before, key=lambda skill: str(skill[1])):
        lines.extend(["[[skills.config]]", "path = " + json.dumps(str(path), ensure_ascii=False),
                      "enabled = " + ("true" if path == entry else "false"), ""])
    data = "\n".join(lines).encode("utf-8")
    digest = hashlib.sha256(data).hexdigest()
    profile = "bago5-workflow-" + digest[:20]
    target = home / (profile + ".config.toml")
    # Verify before making the permanent name observable. A hard link creates
    # the verified file atomically and refuses to replace a pre-existing file.
    with tempfile.NamedTemporaryFile(dir=home, prefix="bago5-probe-", suffix=".config.toml", delete=False) as handle:
        temporary = Path(handle.name)
        handle.write(data)
    try:
        if catalog(cli, env, temporary.name.removesuffix(".config.toml")) != selected:
            raise ValueError("CLI profile did not isolate the selected entry.")
        created = False
        try:
            os.link(temporary, target)
            created = True
        except FileExistsError:
            if target.is_symlink() or not target.is_file() or target.read_bytes() != data:
                raise FileExistsError("Refusing to replace a different or linked profile.")
        try:
            if catalog(cli, env, profile) != selected:
                raise ValueError("Final CLI profile cannot be verified; launch refused.")
        except Exception:
            if created and target.is_file() and target.samefile(temporary):
                target.unlink()
            raise
    finally:
        temporary.unlink(missing_ok=True)
    return env, {"profile": profile, "profile_sha256": digest, "catalog_before_count": len(before),
                 "enabled_skill": selected[0][0], "catalog_after_count": 1}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["prepare", "run"])
    parser.add_argument("--codex")
    parser.add_argument("--codex-home", type=Path, default=Path(os.getenv("CODEX_HOME") or Path.home() / ".codex"))
    parser.add_argument("--skill-md", type=Path, default=ENTRY_FILE)
    parser.add_argument("--prompt", help="Prompt for an interactive run; Codex flags cannot override the profile.")
    args = parser.parse_args(argv)
    if args.prompt is not None and args.action != "run":
        parser.error("--prompt requires run")
    try:
        cli = executable(args.codex)
        env, receipt = prepare(cli, args.codex_home, args.skill_md)
        print(json.dumps(receipt, ensure_ascii=False), flush=True)
        if args.action == "run":
            command = [cli, "--no-daemon", "--profile", receipt["profile"]]
            if args.prompt is not None:
                command += ["--", args.prompt]
            return subprocess.call(command, env=env)
        return 0
    except (OSError, ValueError, KeyError, TypeError, subprocess.TimeoutExpired) as error:
        print(str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
